import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const guideReferences = [
  'awareness.md', 'events.md', 'progress.md', 'delegation.md', 'messaging.md',
  'layout.md', 'notes.md', 'cards.md', 'attachments.md', 'views.md', 'vault.md',
];
export const standaloneGuides = [{ reference: 'interactive.md', output: 'docs/interactive-cards.md' }];
const root = new URL('../', import.meta.url);
const generated = '<!-- Generated by scripts/build-agent-guide.js; edit skills/agent-canvas/references/ instead. -->';
const readReference = name => readFileSync(new URL(`skills/agent-canvas/references/${name}`, root), 'utf8').trim();

export function nestHeadings(markdown) {
  let fence = null;
  return markdown.split('\n').map(line => {
    const marker = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (marker && !fence) fence = marker[1];
    else if (fence && line.trim().match(new RegExp(`^${fence[0]}{${fence.length},}\\s*$`))) fence = null;
    else if (!fence) return line.replace(/^(#{1,5}) /, '#$1 ');
    return line;
  }).join('\n');
}

export function renderGuides() {
  const sections = guideReferences.map(name => nestHeadings(readReference(name)));
  const furtherReading = [
    ['Shared-memory setup', 'shared-memory.md'], ['Precise queries', 'agent-queries.md'],
    ['Notifications', 'canvas-notifications.md'], ['Messaging', 'agent-messaging.md'],
    ['Pending inbox', 'agent-inbox.md'], ['Telemetry', 'agent-telemetry.md'],
    ['Layout', 'agent-canvas-layout.md'], ['Interactive Cards', '../skills/agent-canvas/references/interactive.md'], ['Vault', 'vault.md'],
  ].map(([label, path]) => `- [${label}](${path})`).join('\n');
  return [
    {
      output: 'docs/agent-api.md',
      content: `# Agent Canvas — Agent API Guide\n\n${generated}\n\nCanvas-launched agents normally read only the task references selected by the agent-canvas skill. This comprehensive guide is for browsing, external clients and troubleshooting, not a mandatory per-task download.\n\n${sections.join('\n\n')}\n\n## Further contract details\n\n${furtherReading}\n`,
    },
    ...standaloneGuides.map(({ reference, output }) => ({
      output,
      content: readReference(reference).replace(/^(# [^\n]+)\n/, `$1\n\n${generated}\n`) + '\n',
    })),
  ];
}

export function buildGuides({ check = false } = {}) {
  let current = true;
  for (const { output, content } of renderGuides()) {
    const path = new URL(output, root);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
        console.error(`${output} is stale; run npm run docs:generate`);
        current = false;
      }
    } else {
      writeFileSync(path, content);
      console.log(`Generated ${output}`);
    }
  }
  return current;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/build-agent-guide.js [--check]');
  if (!buildGuides({ check: args.includes('--check') })) process.exitCode = 1;
}
