import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

export async function testMobile({ app, api, ev, send, wait, delay, children }) {
  const screenshot = async name => { if (process.env.CANVAS_MOBILE_SCREENSHOT_PREFIX) await writeFile(`${process.env.CANVAS_MOBILE_SCREENSHOT_PREFIX}-${name}.png`, Buffer.from((await send('Page.captureScreenshot', { format: 'png' })).data, 'base64')); };
  const click = expression => ev(`${expression}.click()`);
  const fill = (selector, value) => ev(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const select = (selector, value) => ev(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const agent = await api('/agents', 'POST', { name: 'Phone Agent', workdir: process.cwd() });
  const child = app.runtime.processes.get(agent.id);
  const card = await api('/cards', 'POST', { content: '# Mobile read only\n\n手機閱讀 $x^2$ and [reference](https://example.com).', tags: ['MobileOnly'], place: false });
  const interactive = await api('/cards', 'POST', { type: 'interactive', title: 'Phone Play', html: '<div>Mobile interactive</div>', javascript: "parent.postMessage({mobilePlay:true}, '*');", place: false });
  await delay(400);
  const before = app.snapshot(false);
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await wait(`!!document.querySelector('.mobile-app') && !!document.querySelector('.mobile-connected')`);
  assert.equal(await ev(`!!document.querySelector('.react-flow')`), false, 'desktop is unmounted, not a hidden resize writer');
  assert.equal(await ev(`document.querySelector('.mobile-header h1').textContent`), 'Board');
  assert.equal(await ev(`!!document.querySelector('.mobile-board [data-agent-id="${agent.id}"]')`), true);
  assert.equal(await ev(`!!document.querySelector('.mobile-board [data-agent-id="${before.agents.find(a => a.workspace === 'card-box')?.id}"]')`), false);
  await screenshot('board');
  const writes = [], observe = req => { if (!['GET', 'HEAD'].includes(req.method)) writes.push(`${req.method} ${req.url}`); };
  app.server.on('request', observe);
  try {
    await ev(`window.mobileWire=[];window.mobileSend=WebSocket.prototype.send;WebSocket.prototype.send=function(data){if(this.url.includes('mobile=1'))window.mobileWire.push(JSON.parse(data));return window.mobileSend.call(this,data)};window.addEventListener('message',event=>{if(event.data?.mobilePlay)window.mobilePlayed=true})`);
    const resizes = child.resizes.length;
    const inputs = child.writes.length;
    await click(`document.querySelector('.mobile-board [data-agent-id="${agent.id}"]')`);
    await wait(`document.querySelector('.mobile-terminal-tools [role="status"]')?.textContent==='Monitoring'`);
    assert.equal(await ev(`document.activeElement?.tagName==='TEXTAREA'`), false);
    assert.equal(await ev(`document.querySelector('.mobile-terminal textarea').readOnly`), true);
    assert.equal(await ev(`window.mobileWire.some(frame=>frame.type==='resize')`), false);
    assert.equal(child.resizes.length, resizes);
    assert.equal(child.writes.length, inputs);
    await screenshot('terminal');
    child.emit('data', Array.from({ length: 120 }, (_, i) => `History ${i}\r\n`).join(''));
    await delay(120);
    const point = await ev(`(()=>{const r=document.querySelector('.mobile-terminal .xterm-screen').getBoundingClientRect();return{x:r.left+60,y:r.top+40}})()`);
    await send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 });
    await send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] });
    await send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: point.x, y: point.y + 140 }] });
    await send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await wait(`Array.from(document.querySelectorAll('.mobile-terminal-tools button')).some(button=>button.textContent==='Latest ↓')`);
    child.emit('data', 'New output while reading history\r\n');
    await delay(100);
    assert.equal(await ev(`Array.from(document.querySelectorAll('.mobile-terminal-tools button')).some(button=>button.textContent==='Latest ↓')`), true, 'new output does not steal scrollback position');
    await click(`Array.from(document.querySelectorAll('.mobile-terminal-tools button')).find(button=>button.textContent==='Latest ↓')`);
    await send('Emulation.setDeviceMetricsOverride', { width: 650, height: 390, deviceScaleFactor: 1, mobile: true });
    await wait(`document.querySelector('.mobile-app').getBoundingClientRect().height<=390`);
    assert.equal(child.resizes.length, resizes, 'orientation does not resize the shared PTY');
    await click(`document.querySelector('.mobile-terminal-tools button')`);
    await wait(`document.querySelector('.mobile-terminal textarea')===document.activeElement && !document.activeElement.readOnly`);
    await send('Input.insertText', { text: '手機中文' });
    await wait(`window.mobileWire.some(frame=>frame.type==='input'&&frame.data.includes('手機中文'))`);
    await delay(40); assert.ok(child.writes.slice(inputs).some(text => text.includes('手機中文')));
    await click(`Array.from(document.querySelectorAll('.mobile-terminal-keys button')).find(button=>button.textContent==='Esc')`);
    await delay(30); assert.ok(child.writes.includes('\u001b'));
    await click(`document.querySelector('.mobile-terminal-tools button')`);
    await wait(`document.querySelector('.mobile-terminal textarea').readOnly`);
    assert.equal(await ev(`document.activeElement?.tagName==='TEXTAREA'`), false);
    const monitoredInputs = child.writes.length;
    await send('Input.insertText', { text: 'must not send' });
    await delay(40); assert.equal(child.writes.length, monitoredInputs);
    await click(`document.querySelector('[aria-label="Back to Board"]')`);
    await click(`document.querySelector('.mobile-tabs button:last-child')`);
    await wait(`!document.querySelector('.mobile-cards').hidden`);
    await select('[aria-label="Browse view"]', '');
    await fill('[aria-label="Search cards"]', '手機閱讀');
    await wait(`document.querySelectorAll('.mobile-cards [data-card-id]').length===1`);
    await click(`document.querySelector('.mobile-cards [data-card-id="${card.id}"]')`);
    await wait(`!!document.querySelector('.mobile-reader .katex')`);
    assert.equal(await ev(`!!document.querySelector('.mobile-reader textarea, .mobile-reader [contenteditable="true"], .mobile-reader [aria-label*="Edit"], .mobile-reader [aria-label*="Delete"]')`), false);
    assert.equal(await ev(`document.querySelector('.mobile-reader .card-markdown').textContent.includes('手機閱讀')`), true);
    await screenshot('card');
    await click(`document.querySelector('[aria-label="Back to Cards"]')`);
    assert.equal(await ev(`document.querySelector('[aria-label="Search cards"]').value`), '手機閱讀');
    await fill('[aria-label="Search cards"]', '');
    await select('[aria-label="Filter tag"]', 'MobileOnly');
    await wait(`document.querySelectorAll('.mobile-cards [data-card-id]').length===1`);
    await select('[aria-label="Filter tag"]', '');
    await fill('[aria-label="Search cards"]', 'Phone Play');
    await click(`document.querySelector('.mobile-cards [data-card-id="${interactive.id}"]')`);
    await wait(`!!document.querySelector('.mobile-reader .interactive-play')`);
    assert.equal(await ev(`document.querySelector('.mobile-reader iframe').getAttribute('sandbox')`), 'allow-scripts');
    await click(`document.querySelector('.mobile-reader .interactive-play')`);
    await wait(`window.mobilePlayed===true`);
    await click(`document.querySelector('[aria-label="Back to Cards"]')`);
    await select('[aria-label="Browse view"]', before.cardBox.views.find(view => view.id !== before.cardBox.activeViewId).id);
    await delay(100);
    assert.deepEqual(writes, [], 'mobile browsing/terminal input creates no HTTP mutations');
    const after = app.snapshot(false);
    assert.deepEqual(after.cardBox, before.cardBox, 'local view selection cannot change shared views/layouts/viewport');
    assert.deepEqual(after.cardPlacements, before.cardPlacements);
    assert.deepEqual(after.agents.map(({ id, x, y, width, height }) => ({ id, x, y, width, height })), before.agents.map(({ id, x, y, width, height }) => ({ id, x, y, width, height })));
  } finally { app.server.removeListener('request', observe); }
  await click(`document.querySelector('.mobile-tabs button:first-child')`);
  await click(`document.querySelector('.mobile-board [data-agent-id="${agent.id}"]')`);
  await wait(`document.querySelector('.mobile-terminal-tools [role="status"]')?.textContent==='Monitoring'`);
  await api(`/agents/${agent.id}/stop`, 'POST', {});
  await wait(`!document.querySelector('.mobile-terminal')`);
  await api(`/agents/${agent.id}/resume`, 'POST', {});
  await wait(`document.querySelector('.mobile-terminal-tools [role="status"]')?.textContent==='Monitoring'`);
  assert.equal(await ev(`document.querySelector('.mobile-terminal textarea').readOnly`), true, 'replacement process never inherits input permission');
  assert.deepEqual(children.at(-1).writes, []);
  // Disconnection disables input immediately; reconnect requires a fresh opt-in.
  await click(`document.querySelector('.mobile-terminal-tools button')`);
  await wait(`document.querySelector('.mobile-terminal-tools [role="status"]')?.textContent==='Input enabled'`);
  await send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await wait(`document.querySelector('.mobile-terminal textarea').readOnly`);
  await send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await wait(`!!document.querySelector('.mobile-connected') && document.querySelector('.mobile-terminal-tools [role="status"]')?.textContent==='Monitoring'`);
  await ev(`WebSocket.prototype.send=window.mobileSend`);
  await send('Emulation.setDeviceMetricsOverride', { width: 1400, height: 1000, deviceScaleFactor: 1, mobile: false });
  await wait(`!!document.querySelector('.react-flow') && !document.querySelector('.mobile-app')`);
  console.log('Mobile browser passed: automatic UI, monitor/input, Chinese text/keys, no PTY resize, read-only local Cards/views/math/Play, replacement/disconnection fencing and desktop restoration.');
}
