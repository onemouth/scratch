import assert from 'node:assert/strict';
import { reportTelemetry } from './telemetry-fixture.js';

// Invoked by the disposable browser fixture only; all PTYs/data are owned.
export async function testScoreboard({ app, api, ev, send, wait, delay, boxAgentId }) {
  const click = expression => ev(expression + '.click()');
  const open = async () => {
    assert.equal(await ev(`document.querySelector('.scoreboard > button').textContent`), 'Board');
    await click(`document.querySelector('.scoreboard > button')`);
    await wait(`(()=>{const r=document.querySelector('.scoreboard-panel')?.getBoundingClientRect();return r&&Math.abs(r.left+r.width/2-innerWidth/2)<1&&Math.abs(r.top-48)<1})()`);
    assert.equal(await ev(`document.querySelector('.scoreboard-panel header strong').textContent`), 'Board');
    assert.equal(await ev(`document.querySelector('.scoreboard-panel').getAttribute('aria-label')`), 'Board');
  };
  const row = id => `.scoreboard-row[data-agent-id="${id}"]`;
  const first = id => wait(`document.querySelector('.scoreboard-row')?.dataset.agentId===${JSON.stringify(id)}`);
  const switchMode = text => ev(`[...document.querySelectorAll('.workspace-nav button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);
  const outside = async () => {
    await send('Input.dispatchMouseEvent', { type: 'mousePressed', x: 5, y: 900, button: 'left', clickCount: 1 });
    await send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 5, y: 900, button: 'left', clickCount: 1 });
    await wait(`!document.querySelector('.scoreboard-panel')`);
  };
  const boxTerminal = await ev(`document.querySelector('.card-box-agent-sidebar .xterm')===window.vaultTerminal`);
  assert.equal(boxTerminal, true);
  const a = await api('/agents', 'POST', { name: 'Scoreboard A', workdir: process.cwd() });
  const b = await api('/agents', 'POST', { name: 'Scoreboard B', workdir: process.cwd() });
  const childA = app.runtime.processes.get(a.id), childB = app.runtime.processes.get(b.id);
  await switchMode('Agent Canvas');
  await open(); await first(b.id);
  assert.equal(await ev(`document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')}).textContent`), '');
  assert.equal(await ev(`!!document.querySelector(${JSON.stringify(row(boxAgentId))})`), false);
  const long = '<b>literal, not HTML</b> 🧋 ' + 'long progress '.repeat(32) + '\nlast line';
  await reportTelemetry(childA, 'progress', { text: long }); await first(a.id);
  const point = await ev(`(()=>{const r=document.querySelector('.scoreboard-panel header strong').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`);
  await send('Input.dispatchMouseEvent', { type: 'mousePressed', ...point, button: 'left', clickCount: 1 });
  await send('Input.dispatchMouseEvent', { type: 'mouseReleased', ...point, button: 'left', clickCount: 1 });
  assert.equal(await ev(`!!document.querySelector('.scoreboard-panel')`), true, 'pointer interaction inside the portaled panel is not an outside click');
  assert.equal(await ev(`document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')}).title`), long);
  assert.equal(await ev(`!!document.querySelector('.scoreboard-progress b')`), false, 'untrusted progress is literal');
  assert.equal(await ev(`getComputedStyle(document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')})).whiteSpace`), 'nowrap');
  assert.equal(await ev(`getComputedStyle(document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')})).textOverflow`), 'ellipsis');
  assert.equal(await ev(`document.querySelectorAll('.node-note').length`), 0, 'no inline progress on either workspace agent');
  await reportTelemetry(childB, 'activity', { state: 'working' }); await first(b.id);
  await reportTelemetry(childA, 'activity', { state: 'idle' }); await first(a.id);
  assert.equal(await ev(`document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')}).textContent`), long);
  assert.equal(await ev(`document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-status')}).textContent`), 'idle');
  await outside();
  await open();
  const writes = [...childA.writes];
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await wait(`!document.querySelector('.scoreboard-panel')`);
  assert.equal(await ev(`document.activeElement===document.querySelector('.scoreboard > button')`), true);
  assert.deepEqual(childA.writes, writes, 'Scoreboard Escape never sends terminal input');
  await switchMode('Card box'); await open();
  await click(`document.querySelector(${JSON.stringify(row(a.id))})`);
  await wait(`!document.querySelector('.scoreboard-panel') && document.querySelector('.brand').textContent.includes('Agent Canvas')`);
  await wait(`document.activeElement?.closest('.react-flow__node-agent')?.dataset.id===${JSON.stringify(a.id)}`);
  assert.equal(await ev(`!!document.querySelector('.app.is-maximized')`), false);
  await wait(`(()=>{const r=document.querySelector('.react-flow__node-agent[data-id="${a.id}"]').getBoundingClientRect();return r.right>0&&r.left<innerWidth&&r.bottom>0&&r.top<innerHeight})()`);
  await ev(`window.scoreboardTerminal=document.querySelector('.react-flow__node-agent[data-id="${a.id}"] .xterm')`);
  await click(`document.querySelector('[aria-label="Maximize Scoreboard A"]')`);
  await wait(`!!document.querySelector('.agent-node.maximized')`);
  assert.equal(await ev(`!!document.querySelector('.scoreboard > button')`), false, 'maximized Agent has no Scoreboard entry');
  await click(`document.querySelector('[aria-label="Return Scoreboard A to whiteboard"]')`);
  await wait(`!!document.querySelector('.scoreboard > button')`);
  assert.equal(await ev(`window.scoreboardTerminal===document.querySelector('.react-flow__node-agent[data-id="${a.id}"] .xterm')`), true);
  await api(`/agents/${a.id}/stop`, 'POST', {});
  await open(); await wait(`!document.querySelector(${JSON.stringify(row(a.id))})`);
  await api(`/agents/${a.id}/resume`, 'POST', {});
  await first(a.id);
  assert.equal(await ev(`document.querySelector(${JSON.stringify(row(a.id) + ' .scoreboard-progress')}).textContent`), '', 'restart clears prior progress');
  await click(`document.querySelector(${JSON.stringify(row(b.id))})`);
  await wait(`document.activeElement?.closest('.react-flow__node-agent')?.dataset.id===${JSON.stringify(b.id)}`);
  await switchMode('Card box');
  await click(`document.querySelector('[aria-label="Maximize Card box"]')`);
  await wait(`!!document.querySelector('.card-box-agent-sidebar.is-maximized')`);
  assert.equal(await ev(`!!document.querySelector('.scoreboard > button')`), false);
  await click(`document.querySelector('[aria-label="Return Card box to whiteboard"]')`);
  await wait(`!!document.querySelector('.scoreboard > button')`);
  const placement = app.snapshot().cardBox.placements[0];
  assert.ok(placement, 'card maximize fixture is present');
  const node = `.react-flow__node-card[data-id="card-box-${placement.cardId}"]`;
  await click(`document.querySelector(${JSON.stringify(node + ' [aria-label="Maximize card ' + placement.cardId + '"]')})`);
  await wait(`!!document.querySelector(${JSON.stringify(node + ' .zettel-card.maximized')})`);
  assert.equal(await ev(`!!document.querySelector('.scoreboard > button')`), false, 'maximized card has no Scoreboard entry');
  await click(`document.querySelector(${JSON.stringify(node + ' [aria-label="Return card ' + placement.cardId + ' to whiteboard"]')})`);
  await wait(`!!document.querySelector('.scoreboard > button')`);
  await open();
  await send('Emulation.setDeviceMetricsOverride', { width: 800, height: 480, deviceScaleFactor: 1, mobile: false });
  await wait(`(()=>{const r=document.querySelector('.scoreboard-panel').getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight&&Math.abs(r.left+r.width/2-innerWidth/2)<1&&Math.abs(r.top-48)<1})()`);
  await send('Emulation.setDeviceMetricsOverride', { width: 1400, height: 1000, deviceScaleFactor: 1, mobile: false });
  await click(`document.querySelector('[aria-label="Close Board"]')`);
  await wait(`!document.querySelector('.scoreboard-panel')`);
  assert.equal(await ev(`document.querySelector('.card-box-agent-sidebar .xterm')===window.vaultTerminal`), true, 'Card box terminal retained');
  await open();
  for (const agent of app.snapshot().agents.filter(agent => agent.workspace !== 'card-box' && agent.status === 'running')) await api(`/agents/${agent.id}/stop`, 'POST', {});
  await wait(`document.querySelectorAll('.scoreboard-row').length===0 && !!document.querySelector('.scoreboard-empty')`);
  assert.equal(await ev(`document.querySelector('.scoreboard-empty').textContent`), 'No running Agent Canvas agents.');
  await click(`document.querySelector('[aria-label="Close Board"]')`);
  await delay(60);
  console.log('Scoreboard browser passed: SHM progress/status ordering, literal one-line hover text, both workspaces, outside/Escape dismissal, navigation/focus, filtering/restart, maximize exclusion and terminal continuity.');
}
