import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { guideReferences, standaloneGuides, renderGuides, nestHeadings } from './build-agent-guide.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const skillRoot = resolve(root, 'skills/agent-canvas');
const read = path => readFileSync(resolve(root, path), 'utf8');
const skill = read('skills/agent-canvas/SKILL.md');
const wordCount = text => text.trim().split(/\s+/u).length;
const links = text => [...text.matchAll(/\[[^\]\n]+\]\(([^)\s]+)\)/g)].map(match => match[1]);
const references = readdirSync(resolve(skillRoot, 'references')).sort();
const ref = name => read(`skills/agent-canvas/references/${name}.md`);

test('Canvas skill follows metadata, relative-path and progressive-disclosure conventions', () => {
  const frontmatter = skill.match(/^---\n([\s\S]+?)\n---\n/);
  assert.ok(frontmatter, 'YAML frontmatter is required');
  const fields = Object.fromEntries(frontmatter[1].split('\n').map(line => {
    const pair = line.match(/^([a-z-]+): (.+)$/);
    assert.ok(pair, 'Metadata uses simple nonempty single-line YAML scalars');
    return pair.slice(1);
  }));
  assert.match(fields.name, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
  assert.ok(fields.name.length <= 64);
  assert.equal(fields.name, basename(skillRoot));
  assert.ok(fields.description.length > 0 && fields.description.length <= 1024);
  assert.ok(fields.compatibility.length > 0 && fields.compatibility.length <= 500);
  assert.ok(skill.split('\n').length <= 100, 'Keep entry point much smaller than the 500-line specification ceiling');
  assert.ok(wordCount(skill) <= 600, 'Do not grow the task router into a full manual');
  assert.match(skill, /relative to \*\*this skill directory\*\*, not your working directory/);
  assert.match(skill, /read only the matching reference/);
  assert.match(skill, /Reuse references already read/);
  assert.match(skill, /Only if a contract is missing\/ambiguous or the backend appears incompatible/);
  assert.doesNotMatch(skill, /Before.*read.*complete guide|read the \*\*current, complete guide\*\*/i);
  const fullGuide = read('docs/agent-api.md');
  for (const task of ['messaging', 'progress']) {
    assert.ok(skill.length + ref(task).length < fullGuide.length / 4, `${task}: routine loading must stay below 25% of the full guide's characters`);
  }

  const targets = links(skill);
  assert.deepEqual(targets.map(path => basename(path)).sort(), [...references, 'cards.md'].sort());
  for (const target of targets) {
    assert.match(target, /^references\/[a-z-]+\.md$/);
    assert.ok(existsSync(resolve(skillRoot, target)), target);
  }
  for (const name of references) {
    const text = ref(name.slice(0, -3));
    assert.ok(wordCount(text) <= 1600, `${name}: split unrelated detail before growing a task reference`);
    assert.ok(text.split('\n').length <= 200, `${name}: keep references focused`);
    assert.ok(links(text).every(target => target.startsWith('#')), `${name}: no nested file-reference chains`);
    if (text.split('\n').length > 100) assert.match(text, /^## Contents$/m, `${name}: long references need a contents list`);
  }
});

test('Canonical references generate both public manuals without drift, from any workdir', () => {
  for (const { output } of renderGuides()) {
    assert.ok(read('.gitignore').split('\n').includes(`/${output}`), `${output}: generated manuals must be ignored`);
  }
  const { scripts } = JSON.parse(read('package.json'));
  for (const hook of ['postinstall', 'predev', 'prestart', 'pretest', 'prebuild']) {
    assert.ok(scripts[hook].includes('node scripts/build-agent-guide.js'), `${hook}: generate ignored guide before use`);
  }
  const covered = [...guideReferences, ...standaloneGuides.map(item => item.reference)];
  assert.deepEqual(covered.sort(), references);
  for (const { output, content } of renderGuides()) {
    assert.equal(read(output), content, `${output}: run npm run docs:generate`);
    assert.match(content, /Generated by scripts\/build-agent-guide.js/);
    for (const target of links(content)) {
      if (target.startsWith('#') || /^[a-z]+:/i.test(target)) continue;
      assert.ok(existsSync(resolve(root, dirname(output), target.split('#')[0])), `${output}: broken link ${target}`);
    }
  }
  const result = spawnSync(process.execPath, [resolve(root, 'scripts/build-agent-guide.js'), '--check'], {
    cwd: dirname(root), encoding: 'utf8',
  });
  assert.equal(result.status, 0, result.stderr);
});

test('Guide checks reject stale or missing output without silently rewriting it', async () => {
  const fixture = await mkdtemp(resolve(tmpdir(), 'canvas-skill-guide-'));
  try {
    await mkdir(resolve(fixture, 'scripts'));
    await mkdir(resolve(fixture, 'docs'));
    await writeFile(resolve(fixture, 'package.json'), '{"type":"module"}');
    await cp(resolve(root, 'scripts/build-agent-guide.js'), resolve(fixture, 'scripts/build-agent-guide.js'));
    await cp(resolve(skillRoot, 'references'), resolve(fixture, 'skills/agent-canvas/references'), { recursive: true });
    for (const { output, content } of renderGuides()) await writeFile(resolve(fixture, output), content);
    await writeFile(resolve(fixture, 'docs/agent-api.md'), 'stale output\n');
    await rm(resolve(fixture, 'docs/interactive-cards.md'));
    const result = spawnSync(process.execPath, [resolve(fixture, 'scripts/build-agent-guide.js'), '--check'], { cwd: fixture, encoding: 'utf8' });
    assert.equal(result.status, 1, result.stderr);
    assert.match(result.stderr, /docs\/agent-api.md is stale/);
    assert.match(result.stderr, /docs\/interactive-cards.md is stale/);
    assert.match(result.stderr, /npm run docs:generate/);
    assert.equal(readFileSync(resolve(fixture, 'docs/agent-api.md'), 'utf8'), 'stale output\n');
    assert.equal(existsSync(resolve(fixture, 'docs/interactive-cards.md')), false);
    // A fresh checkout has no ignored API guide: generation must recreate it.
    await rm(resolve(fixture, 'docs/agent-api.md'));
    const generated = spawnSync(process.execPath, [resolve(fixture, 'scripts/build-agent-guide.js')], { cwd: fixture, encoding: 'utf8' });
    assert.equal(generated.status, 0, generated.stderr);
    for (const { output, content } of renderGuides()) assert.equal(readFileSync(resolve(fixture, output), 'utf8'), content);
  } finally { await rm(fixture, { recursive: true, force: true }); }
});

